def single_scale_retinex(image, sigma=30):

    image = image.astype(np.float32) + 1.0

    blur = cv2.GaussianBlur(image, (0, 0), sigma)

    retinex = np.log(image) - np.log(blur)

    return retinex

def multi_scale_retinex(image):

    sigmas = [15, 80, 250]

    retinex = np.zeros_like(image, dtype=np.float32)

    for sigma in sigmas:
        retinex += single_scale_retinex(image, sigma)

    retinex /= len(sigmas)

    return retinex

def color_restoration(image):

    image = image.astype(np.float32) + 1

    intensity = np.sum(image, axis=2, keepdims=True)

    restoration = np.log(125 * image) - np.log(intensity)

    return restoration

def enhance_image(image):

    image = image.astype(np.float32)

    retinex = multi_scale_retinex(image)

    restore = color_restoration(image)

    result = retinex * restore

    for i in range(3):

        channel = result[:, :, i]

        channel = cv2.normalize(
            channel,
            None,
            0,
            255,
            cv2.NORM_MINMAX
        )

        result[:, :, i] = channel

    return result.astype(np.uint8)


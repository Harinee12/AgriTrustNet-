    predictions=[]

    model.eval()
    enable_dropout(model)

    with torch.no_grad():

        for _ in range(samples):

            disease_out, severity_out, confidence_out = model(image)

            prob = torch.softmax(
                disease_out,
                dim=1
            )

            predictions.append(
                prob.cpu().numpy()
            )


    predictions = np.array(predictions)

    mean_prediction = predictions.mean(axis=0)


    # entropy based uncertainty
    entropy = -np.sum(
        mean_prediction * np.log(mean_prediction + 1e-8)
    )


    confidence = np.max(mean_prediction)


    return confidence, entropy


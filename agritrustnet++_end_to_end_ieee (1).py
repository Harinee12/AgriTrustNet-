def segment_leaf(image):

    hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)

    lower_green = np.array([20,20,20])
    upper_green = np.array([100,255,255])

    mask = cv2.inRange(
        hsv,
        lower_green,
        upper_green
    )

    return mask

def detect_disease_region(image):

    hsv = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2HSV
    )


    lower_disease = np.array(
        [5,20,20]
    )

    upper_disease = np.array(
        [40,255,255]
    )


    disease_mask = cv2.inRange(
        hsv,
        lower_disease,
        upper_disease
    )


    return disease_mask

def calculate_severity(image):

    leaf_mask = segment_leaf(image)

    disease_mask = detect_disease_region(image)


    leaf_pixels = np.sum(leaf_mask > 0)

    disease_pixels = np.sum(disease_mask > 0)


    if leaf_pixels == 0:

        return 0, "Healthy"


    severity_percentage = (
        disease_pixels /
        leaf_pixels
    ) * 100



    if severity_percentage < 10:

        label = "Healthy"


    elif severity_percentage < 30:

        label = "Mild"


    elif severity_percentage < 60:

        label = "Moderate"


    else:

        label = "Severe"



    return severity_percentage, label


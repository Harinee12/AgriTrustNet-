def train_one_epoch(model, loader):

    model.train()

    running_loss = 0

    disease_correct = 0
    severity_correct = 0

    total = 0


    for images, disease_labels, severity_labels in loader:


        images = images.to(device)
        disease_labels = disease_labels.to(device)
        severity_labels = severity_labels.to(device)


        optimizer.zero_grad()


        # Forward pass
        disease_out, severity_out, confidence_out = model(images)



        # Confidence target
        confidence_target = (
            disease_out.argmax(1) == disease_labels
        ).float().unsqueeze(1)



        # Losses
        loss_disease = disease_loss_fn(
            disease_out,
            disease_labels
        )


        loss_severity = severity_loss_fn(
            severity_out,
            severity_labels
        )


        loss_confidence = confidence_loss_fn(
            confidence_out,
            confidence_target
        )


        total_loss = (
            loss_disease
            +
            0.5 * loss_severity
            +
            0.2 * loss_confidence
        )


        # Backpropagation

        total_loss.backward()

        optimizer.step()



        running_loss += total_loss.item()



        disease_pred = disease_out.argmax(1)

        severity_pred = severity_out.argmax(1)



        disease_correct += (
            disease_pred == disease_labels
        ).sum().item()


        severity_correct += (
            severity_pred == severity_labels
        ).sum().item()


        total += images.size(0)



    avg_loss = running_loss / len(loader)

    disease_acc = 100 * disease_correct / total

    severity_acc = 100 * severity_correct / total



    return avg_loss, disease_acc, severity_acc


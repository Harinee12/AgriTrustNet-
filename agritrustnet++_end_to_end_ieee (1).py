class FeatureExtractor(nn.Module):

    def __init__(self):

        super().__init__()


        # EfficientNetV2-S

        efficient = models.efficientnet_v2_s(
            weights="DEFAULT"
        )

        self.efficientnet = nn.Sequential(
            *list(efficient.children())[:-1]
        )


        # ConvNeXt-Tiny

        convnext = models.convnext_tiny(
            weights="DEFAULT"
        )

        self.convnext = nn.Sequential(
            *list(convnext.children())[:-1]
        )



    def forward(self,x):

        f1=self.efficientnet(x)

        f2=self.convnext(x)


        f1=torch.flatten(
            f1,
            1
        )


        f2=torch.flatten(
            f2,
            1
        )


        return f1,f2




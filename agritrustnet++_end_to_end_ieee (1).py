import cv2
import numpy as np


def calculate_severity(image_path):

    image=cv2.imread(image_path)

    if image is None:
        return None,None


    image=cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB
    )


    # Convert RGB to HSV

    hsv=cv2.cvtColor(
        image,
        cv2.COLOR_RGB2HSV
    )


    # Green leaf mask

    lower_green=np.array([25,30,20])
    upper_green=np.array([95,255,255])


    leaf_mask=cv2.inRange(
        hsv,
        lower_green,
        upper_green
    )


    leaf_pixels=np.sum(leaf_mask>0)


    if leaf_pixels==0:
        return None,None



    # Non-green region = disease region

    disease_mask=255-leaf_mask


    disease_pixels=np.sum(
        disease_mask>0
    )


    severity_percentage=(disease_pixels/leaf_pixels)*100



    if severity_percentage < 25:

        label="Mild"


    elif severity_percentage < 50:

        label="Moderate"


    elif severity_percentage < 75:

        label="Severe"


    else:

        label="Very_Severe"



    return severity_percentage,label


class AttentionModule(nn.Module):

    def __init__(self, dim):
        super().__init__()

        self.attention = nn.Sequential(
            nn.Linear(dim, dim),
            nn.Sigmoid()
        )


    def forward(self,x):

        weights = self.attention(x)

        return x * weights



class AgriHeads(nn.Module):

    def __init__(self):

        super().__init__()

        # Attention
        self.attention = AttentionModule(1024)


        # Disease classification
        self.disease_head = nn.Sequential(

            nn.Linear(1024,512),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(512,5)

        )


        # Severity classification
        self.severity_head = nn.Sequential(

            nn.Linear(1024,512),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(512,5)

        )


        # Confidence estimation
        self.confidence_head = nn.Sequential(

            nn.Linear(1024,256),
            nn.ReLU(),
            nn.Linear(256,1),
            nn.Sigmoid()

        )



    def forward(self,x):

        attended = self.attention(x)


        disease = self.disease_head(attended)

        severity = self.severity_head(attended)

        confidence = self.confidence_head(attended)


        return disease, severity, confidence


class AgriTrustNetPP(nn.Module):

    def __init__(self):

        super().__init__()


        self.feature_extractor = FeatureExtractor()


        self.feature_fusion = FeatureFusion()


        self.attention = AttentionFusion()


        self.heads = PredictionHeads()



    def forward(self,x):


        # Feature extraction

        f1,f2 = self.feature_extractor(x)



        # Fusion

        fused = self.feature_fusion(
            f1,
            f2
        )



        # Attention refinement

        attended = self.attention(
            fused
        )



        # Multi task outputs

        disease, severity, confidence = self.heads(
            attended
        )


        return (
            disease,
            severity,
            confidence
        )

